#!/usr/bin/env python3
"""Build Mantiq al-Tayr per-bayt notes from a compact authoring format.

    python3 scripts/mantiq-notes.py <dir-with-slug.txt-files>

Format of <slug>.txt (one file per section):
    @<ganjoor part id>
    <bayt n> | <meaning> | <word>: <gloss>; <word>: <gloss> | <mystical reading>
The last two fields may be empty or omitted. Writes src/data/library/mantiq/notes/<slug>.json and
regenerates notes/load.gen.ts. A section is 'complete' when every bayt in its text has a note.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MQ = ROOT / 'src/data/library/mantiq'
OUT = MQ / 'notes'

def build(src: Path):
    slug = src.stem
    text = json.loads((MQ / 'text' / f'{slug}.json').read_text())
    valid = {f"{p['id']}:{c['n']}" for p in text['parts'] for c in p['couplets']}
    notes, part = {}, None
    for i, raw in enumerate(src.read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('@'):
            part = int(line[1:]); continue
        f = [x.strip() for x in line.split('|')]
        n = int(f[0]); key = f'{part}:{n}'
        if key not in valid:
            raise SystemExit(f'{src}:{i}: {key} is not a bayt of {slug}')
        if key in notes:
            raise SystemExit(f'{src}:{i}: duplicate {key}')
        if len(f) < 2 or not f[1]:
            raise SystemExit(f'{src}:{i}: missing meaning')
        note = {'meaning': f[1]}
        if len(f) > 2 and f[2]:
            gl = []
            for g in f[2].split(';'):
                if not g.strip(): continue
                w, _, m = g.partition(':')
                if not m.strip(): raise SystemExit(f'{src}:{i}: gloss without meaning: {g}')
                gl.append({'word': w.strip(), 'meaning': m.strip()})
            note['glossary'] = gl
        if len(f) > 3 and f[3]:
            note['artistry'] = f[3]
        notes[key] = note
    status = 'complete' if valid <= notes.keys() else 'in-progress'
    order = [f"{p['id']}:{c['n']}" for p in text['parts'] for c in p['couplets']]
    doc = {'slug': slug, 'status': status, 'notes': {k: notes[k] for k in order if k in notes}}
    (OUT / f'{slug}.json').write_text(json.dumps(doc, ensure_ascii=False, separators=(',', ':')) + '\n')
    print(f'{slug:14} {len(notes):4}/{len(valid):4} {status}')

def main():
    OUT.mkdir(exist_ok=True)
    for f in sorted(Path(sys.argv[1]).glob('*.txt')):
        build(f)
    slugs = sorted(p.stem for p in OUT.glob('*.json'))
    (OUT / 'load.gen.ts').write_text(
        '// Generated by scripts/mantiq-notes.py. One lazy chunk per section that has notes.\n'
        "import type { MantiqNotes } from '../types'\n\n"
        'export const notesLoaders: Record<string, () => Promise<MantiqNotes>> = {\n'
        + ''.join(f"  '{s}': () => import('./{s}.json').then((m) => m.default as MantiqNotes),\n" for s in slugs)
        + '}\n'
    )

if __name__ == '__main__':
    main()
